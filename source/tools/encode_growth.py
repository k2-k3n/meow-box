"""Bake the five Meow Box poses into RGB565 sprites. Requires Pillow."""
from collections import deque
from pathlib import Path
import re
from PIL import Image

root = Path(__file__).resolve().parents[1]
sheet = Image.open(root / "assets/size-transition-v2.png").convert("RGB")
header = (root / "src/clay_art.h").read_text()
bounds = [0, 330, 644, 974, 1335, 1774]
heights = [80, 95, 109, 118, 126]
mouths = [(190, 486), (493, 450), (818, 435), (1168, 413), (1559, 389)]
names = ["Kitten", "Young", "Tabby", "Cub", "Lion"]
old_names = ["Kitten", "Kitten", "Tabby", "Lion", "Lion"]
old_rects = [(23,15), (23,15), (28,22), (39,30), (39,30)]

def encode(r,g,b):
    return max(1, (r>>3)<<11 | (g>>2)<<5 | b>>3)

def sprite(cell):
    image = cell.convert("RGBA")
    p = image.load()
    width, height = image.size
    queue = deque([(0, 0)])
    while queue:
        x,y = queue.popleft()
        r,g,b,a = p[x,y]
        if not a or max(r,g,b) > 63 or max(r,g,b)-min(r,g,b) > 16:
            continue
        p[x,y] = (0,0,0,0)
        for nx,ny in ((x-1,y),(x+1,y),(x,y-1),(x,y+1)):
            if 0<=nx<width and 0<=ny<height:
                queue.append((nx,ny))
    return image

def emit(name, values):
    lines = [",".join(map(str,values[i:i+24]))+"," for i in range(0,len(values),24)]
    return f"static const uint16_t {name}[] = {{\n" + "\n".join(lines) + "\n};\n"

output = "// Generated by tools/encode_growth.py.\n#pragma once\n"
rows = []
for i, name in enumerate(names):
    left = bounds[i]
    cut = sprite(sheet.crop((left,100,bounds[i+1],687)))
    x0,y0,x1,y1 = cut.getbbox()
    cut = cut.crop((x0,y0,x1,y1))
    h = heights[i]
    w = round(cut.width*h/cut.height)
    center_x = round((mouths[i][0]-left-x0)*w/cut.width)
    center_y = round((mouths[i][1]-100-y0)*h/cut.height)
    cat = cut.resize((w,h),Image.Resampling.LANCZOS)
    data = [encode(r,g,b) if a>=128 else 0 for r,g,b,a in cat.get_flattened_data()]
    ow,oh = old_rects[i]
    raw = re.search(rf"kClay{old_names[i]}Mouth\[\] = \{{(.*?)\}};",header,re.S)[1]
    values = [int(v) for v in raw.split(",") if v.strip()]
    # Reuse the original mouth's interior, leaving the new muzzle's own color at its edges.
    mask = Image.new("RGBA",(ow,oh))
    for y in range(oh):
        for x in range(ow):
            c = values[y*ow+x]
            r,g,b = (c>>11)*255//31, ((c>>5)&63)*255//63, (c&31)*255//31
            inner = ((x-(ow-1)*.5)/(ow*.32))**2 + ((y-(oh-1)*.49)/(oh*.34))**2 < 1
            if inner and c and (r+g+b<180 or (r>g*1.25 and b>g*1.15)):
                mask.putpixel((x,y),(r,g,b,255))
    mw,mh = round(w*.42),round(h*.20)
    mx,my = center_x-mw//2,center_y-mh//2
    mask = mask.resize((mw,mh),Image.Resampling.LANCZOS)
    wet = [encode(r,g,b) if a>=128 else 0 for r,g,b,a in mask.get_flattened_data()]
    assert 0<=mx<mx+mw<=w and 0<my<my+mh<h and sum(c!=0 for c in wet)>8
    output += emit(f"kGrowth{name}",data)
    output += emit(f"kGrowth{name}Mouth",wet)
    rows.append(f"    {{kGrowth{name}, {w}, {h}, kGrowth{name}Mouth, {mx}, {my}, {mw}, {mh}}},")
(root/"src/growth_art.h").write_text(output+"static const ClayCat kGrowthCats[] = {\n"+"\n".join(rows)+"\n};\n")
