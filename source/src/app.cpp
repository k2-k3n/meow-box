// Meow Box: a cat sings whatever you play. MIT.
//
//   SELECTOR   turn: the cat's SIZE (kitten .. lion)      click: meow length (MEW / MEOW / MEEOOOW)
//   CUSTOMIZE  turn: MEOW mix             click: purr on/off      long press: reset
//
// The Web, Mobile and MIDI controllers (controller/, CCs on channel 1, see README.md) reach every
// setting the knobs reach, plus BEND, the purr's amount and LEVEL, and three hold pads: ROAR
// (the lion, full voice, wide bend), MEW (a kitten's short mew) and HUSH (the dry guitar).
//
// The sound is the nested dsp/ pack (Meow Voice); this file is the cat. The App cannot read
// the pack's state, so the cat acts on the input meter: a hard pick opens its mouth for one
// meow, and silence sends it to sleep. The artwork is baked
// RGB565 art (clay_art.h, generated by tools/encode_clay.swift).
#include <resona/platform.h>
#include <resona/startup_helpers.h>
#include "kit.h"
#include "clay_art.h"
#include "meow_splash.h"
#include "controller_link.h"

namespace {

const resona_platform *P;
const char kPack[] = "org.resona.creative.meow-box.voice";   // dsp/resona.project.json
const char kPackVersion[] = "1.0.3";
const uint32_t kPackCrc32 = 2954291668u;
enum { MIX, SIZE, LENGTH, BEND, PURR, LEVEL, PARAMS };
const float kLengths[3] = {260.0f, 550.0f, 1050.0f};
const char *const kLengthName[3] = {"MEW", "MEOW", "MEEOOOW"};

struct SavedV1 { uint32_t magic; int size, mix, length, purr; };
struct Saved { uint32_t magic; int size, mix, length, purr, bend, purr_amt, level; };
const uint32_t kMagicV1 = 0x4D454F31u;   // "MEO1"
const uint32_t kMagic = 0x4D454F32u;     // "MEO2"

// The controllers' MIDI map: CC on channel 1 (controller/shared/profile.js says the same).
enum { CC_SIZE = 20, CC_LENGTH, CC_MIX, CC_BEND, CC_PURR, CC_PURR_AMT, CC_LEVEL, CC_ROAR = 30, CC_MEW, CC_HUSH };

struct State {
    kit::Audio audio;
    kit::Saver saver;
    Saved s;
    uint32_t ms, meow_at, idle, touched_at;
    uint8_t lastInput;
    float visualSize;
    int meowing, touched;   // touched: 1 SIZE, 2 MEOW mix (whose value to show for a moment)
    int roar, mew, hush;    // pads held on a controller
    ctl::Link link;
};

ctl::Bind kBind[10];
void bind(State *st)
{
    Saved &s = st->s;
    const ctl::Bind b[10] = {
        {CC_SIZE, ctl::RANGE, 0, 100, &s.size}, {CC_LENGTH, ctl::STEPS, 0, 2, &s.length},
        {CC_MIX, ctl::RANGE, 0, 100, &s.mix}, {CC_BEND, ctl::RANGE, 0, 100, &s.bend},
        {CC_PURR, ctl::STEPS, 0, 1, &s.purr}, {CC_PURR_AMT, ctl::RANGE, 0, 100, &s.purr_amt},
        {CC_LEVEL, ctl::RANGE, -12, 6, &s.level},
        {CC_ROAR, ctl::TRIGGER, 0, 1, nullptr}, {CC_MEW, ctl::TRIGGER, 0, 1, nullptr}, {CC_HUSH, ctl::TRIGGER, 0, 1, nullptr},
    };
    for (int i = 0; i < 10; ++i) kBind[i] = b[i];
}


// The pads override the settings while held: ROAR wins over MEW; HUSH mutes the cat.
int size_now(const State *st) { return st->roar ? 100 : (st->mew ? 0 : st->s.size); }
int length_now(const State *st) { return st->roar ? 2 : (st->mew ? 0 : st->s.length); }

void push(State *st)
{
    kit::audio_set(P, st->audio, MIX, st->hush ? 0.0f : (st->roar ? 100.0f : (float)st->s.mix));
    kit::audio_set(P, st->audio, SIZE, (float)size_now(st));
    kit::audio_set(P, st->audio, LENGTH, kLengths[length_now(st)]);
    kit::audio_set(P, st->audio, BEND, st->roar ? 100.0f : (float)st->s.bend);
    kit::audio_set(P, st->audio, PURR, st->s.purr ? (float)st->s.purr_amt : 0.0f);
    kit::audio_set(P, st->audio, LEVEL, (float)st->s.level);
}

void defaults(State *st) { st->s = {kMagic, 45, 80, 1, 0, 60, 45, 0}; }

/* ---- the cat ---------------------------------------------------------------------------- */

// Sample the same scaled coordinates for the body and its animated mouth.
uint16_t cat_pixel(const ClayCat &cat, int sx, int sy, float mouth)
{
    if (sx < 0) return 0;
    const uint16_t body = cat.pixels[sy * cat.w + sx];
    const int mx = sx - cat.mx, my = sy - cat.my;
    if (!body || mouth <= 0 || mx < 0 || mx >= cat.mw || my < 0 || my >= cat.mh) return body;
    const uint16_t color = cat.mouth[my * cat.mw + mx];
    if (!color) return body;
    const int edgeX = kit::clampi(cat.mw - 1 - mx, 0, mx);
    const int edgeY = kit::clampi(cat.mh - 1 - my, 0, my);
    const int edge = edgeX < edgeY ? edgeX : edgeY;
    return kit::mix(body, color, mouth * kit::clampf(edge * .25f, 0.0f, 1.0f));
}

void draw_cat(kit::Canvas &c, float size, int floor, float mouth)
{
    // Original heights at 0, 50 and 100. The paws stay on the same floor line.
    const float height = size < 50 ? 80.0f + size * .58f : 109.0f + (size - 50) * .34f;
    const int h = (int)(height + .5f);
    const int boundary = size < 50 ? 34 : 68;
    const int lower = size < 50 ? 0 : 1;
    const float t = kit::clampf((size - (boundary - 4)) / 8.0f, 0.0f, 1.0f);
    const float blend = t * t * (3.0f - 2.0f * t);
    const ClayCat &a = kClayCats[lower];
    const ClayCat &b = kClayCats[lower + 1];
    const int wa = (h * a.w + a.h / 2) / a.h;
    const int wb = (h * b.w + b.h / 2) / b.h;
    const int width = blend <= 0 ? wa : blend >= 1 ? wb : wa > wb ? wa : wb;
    const int xa = (c.W - wa) / 2, xb = (c.W - wb) / 2;
    const int left = (c.W - width) / 2;
    int16_t sampleA[c.W], sampleB[c.W];
    float reveal[c.W];
    for (int x = left; x < left + width; ++x) {
        sampleA[x] = x >= xa && x < xa + wa ? (x - xa) * a.w / wa : -1;
        sampleB[x] = x >= xb && x < xb + wb ? (x - xb) * b.w / wb : -1;
        // Reveal the next character across a narrow edge to avoid two superimposed faces.
        reveal[x] = kit::clampf((blend * (width + 8) - (x - left)) / 8.0f, 0.0f, 1.0f);
    }
    for (int y = 0; y < h; ++y) {
        const int ya = y * a.h / h, yb = y * b.h / h;
        uint16_t *row = c.px + (floor - h + y) * c.stride;
        for (int x = left; x < left + width; ++x) {
            const uint16_t first = blend < 1 ? cat_pixel(a, sampleA[x], ya, mouth) : 0;
            const uint16_t second = blend > 0 ? cat_pixel(b, sampleB[x], yb, mouth) : 0;
            if (first || second)
                row[x] = blend <= 0 ? first : blend >= 1 ? second :
                         kit::mix(first ? first : row[x], second ? second : row[x], reveal[x]);
        }
    }
}

void draw(State *st)
{
    kit::Canvas c;
    if (!c.begin(P)) return;
    const uint16_t ink = kit::rgb(34, 19, 37), cream = kit::rgb(255, 240, 214);
    const int length = length_now(st);
    const int kind = st->visualSize < 34 ? 0 : (st->visualSize < 68 ? 1 : 2);
    const bool asleep = st->idle > 9000;
    float open = 0.0f, prog = 1.0f;
    if (st->meowing) {
        prog = (float)(st->ms - st->meow_at) / kLengths[length];
        if (prog >= 1.0f) st->meowing = 0;
        else open = resona_sinf(3.14159f * kit::clampf(prog * 1.15f, 0.0f, 1.0f));
    }

    for (int y = 0; y < c.H; ++y)
        for (int x = 0; x < c.W; ++x)
            c.px[y * c.stride + x] = kClayRoom[y * c.W + x];

    const int bounce = st->meowing && prog < 0.18f ? 3 : 0;
    const int breathing = (st->ms / 850u) & 1u;
    const float amount = kit::clampf((open - .12f) / .76f, 0.0f, 1.0f);
    draw_cat(c, st->visualSize, 153 - bounce + breathing, amount * amount * (3.0f - 2.0f * amount));

    c.text_s(9, 9, 2, cream, ink, "MEOW BOX");
    static const char *const modes[] = {"KITTEN", "TABBY", "LION"};
    c.text_s(9, 30, 1, cream, ink, modes[kind]);
    if (asleep) c.text_s(227, 54, 2, cream, ink, "Zz");
    else if (open > .2f) c.text_s(227, 54, 1, cream, ink, kind == 2 ? "ROAR" : kLengthName[length]);
    else if (st->s.purr) c.text_s(227, 54, 1, cream, ink, "PURR");

    char mix[16];
    P->format(mix, sizeof mix, "%d%%", st->hush ? 0 : st->roar ? 100 : st->s.mix);
    c.text_s(244, 117, 1, cream, ink, "MIX");
    c.text_s(244, 130, 2, cream, ink, mix);
    if (st->touched == 1 && st->ms - st->touched_at < 1300u) {
        char value[16];
        P->format(value, sizeof value, "SIZE %d", st->s.size);
        c.text_s(9, 140, 1, cream, ink, value);
    }
    c.banner(kit::audio_message(st->audio, "INSTALL MEOW VOICE IN LAB"), ink, kit::rgb(252, 236, 150));
    c.present(P);
}

/* ---- the App ---------------------------------------------------------------------------- */

int init(void *state, const resona_platform *platform)
{
    State *st = static_cast<State *>(state);
    P = platform;
    const int splash = resona_startup_splash_apply(P, kMeowSplash, sizeof kMeowSplash);
    if (splash < 0 && splash != RESONA_ERR_UNSUPPORTED)
        P->log("Meow Box: boot animation could not be saved");
    defaults(st);
    Saved v;
    SavedV1 v1;
    if (kit::load(P, v, kMagic)) st->s = v;
    else if (kit::load(P, v1, kMagicV1)) { st->s.size = v1.size; st->s.mix = v1.mix; st->s.length = v1.length; st->s.purr = v1.purr; }
    Saved &s = st->s;
    s.size = kit::clampi(s.size, 0, 100); s.mix = kit::clampi(s.mix, 0, 100); s.length = kit::clampi(s.length, 0, 2);
    s.purr = s.purr ? 1 : 0; s.bend = kit::clampi(s.bend, 0, 100); s.purr_amt = kit::clampi(s.purr_amt, 0, 100);
    s.level = kit::clampi(s.level, -12, 6);
    st->visualSize = (float)size_now(st);
    bind(st);
    push(st);
    return 0;
}

void event(void *state, const resona_app_event *ev)
{
    State *st = static_cast<State *>(state);
    if (kit::audio_event(P, st->audio, ev, st->ms)) return;
    ctl::Msg m;
    if (ctl::receive(P, st->link, kBind, 10, ev, m)) {
        if (!m.changed) return;
        if (m.cc == CC_ROAR) st->roar = m.down;
        else if (m.cc == CC_MEW) st->mew = m.down;
        else if (m.cc == CC_HUSH) st->hush = m.down;
        else kit::save_later(st->saver, st->ms);
        if (m.cc == CC_SIZE) { st->touched = 1; st->touched_at = st->ms; }
        if (m.cc == CC_MIX) { st->touched = 2; st->touched_at = st->ms; }
        st->idle = 0;
        if (m.cc != CC_HUSH && (m.cc < CC_ROAR || m.down)) { st->meowing = 1; st->meow_at = st->ms; }
        push(st);
        return;
    }
    if (ev->kind != RESONA_APP_EV_INPUT) return;
    if (ev->u.input.input != RESONA_INPUT_SELECTOR &&
        ev->u.input.input != RESONA_INPUT_CUSTOMIZE) return;
    const int top = ev->u.input.input == RESONA_INPUT_SELECTOR;
    const int kind = (int)ev->u.input.kind, v = ev->u.input.value;
    if (kind == RESONA_EVENT_TURN) {
        if (top) st->s.size = kit::clampi(st->s.size + v * 2, 0, 100);
        else st->s.mix = kit::clampi(st->s.mix + v * 2, 0, 100);
        st->touched = top ? 1 : 2;
        st->touched_at = st->ms;
    } else if (kind == RESONA_EVENT_CLICK) {
        if (top) st->s.length = (st->s.length + 1) % 3;
        else st->s.purr ^= 1;
    } else if (kind == RESONA_EVENT_LONG && !top) {
        defaults(st);
    } else {
        return;
    }
    st->idle = 0;
    st->meowing = 1; st->meow_at = st->ms;   // the cat answers every touch
    push(st);
    kit::save_later(st->saver, st->ms);
}

void frame(void *state, uint32_t ms)
{
    State *st = static_cast<State *>(state);
    st->ms += ms;
    kit::audio_tick(P, st->audio, kPack, PARAMS, st->ms, kPackVersion, kPackCrc32);
    uint8_t input, output, cpu;
    P->meters(&input, &output, &cpu);
    const bool pick = input >= 5 && input >= st->lastInput + 2;
    st->lastInput = input;
    kit::save_tick(P, st->saver, st->s, st->ms);
    ctl::sync(P, st->link, kBind, 10, st->ms);
    if (input >= 2) st->idle = 0; else st->idle += ms;
    const uint32_t retriggerMs = (uint32_t)(kLengths[length_now(st)] * 0.25f);
    if (pick && (!st->meowing || st->ms - st->meow_at > retriggerMs)) {
        st->meowing = 1;
        st->meow_at = st->ms;
    }
    const float difference = (float)size_now(st) - st->visualSize;
    if (difference > -.15f && difference < .15f) st->visualSize = (float)size_now(st);
    else st->visualSize += difference * (1.0f - resona_expf(-(float)ms / 36.0f));
    draw(st);
}

const resona_app kApp = {
    RESONA_PLATFORM_VERSION, sizeof(resona_app),
    RESONA_APP_ID, RESONA_APP_NAME, RESONA_APP_VERSION,
    sizeof(State), 0,
    init, event, frame,
};

}  // namespace

extern "C" const resona_app *resona_app_get(void) { return &kApp; }
